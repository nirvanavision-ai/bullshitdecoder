/**
 * build-standalone.js — bundles the modular source into one portable HTML file.
 *
 * Output: index.html — works from file:// with no server, no modules, no
 * network. Useful for emailing to someone, putting on a USB stick, or hosting
 * anywhere that can't serve .js with the right MIME type.
 *
 * Run: npm run build
 *
 * Implementation note worth keeping: the replacements use *function* callbacks.
 * A plain string replacement would interpret `$$`, `$&`, and `` $` `` inside the
 * bundled JavaScript as special patterns and splice the document into itself —
 * which silently produced a duplicate-declaration crash the first time round.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(fileURLToPath(import.meta.url));
const read = f => readFileSync(join(ROOT, f), "utf8");

/** Strip ES module syntax so the sources can be concatenated into one classic script. */
const strip = f => read(f)
  .replace(/^\s*import\s+[^;]+;\s*$/gm, "")
  .replace(/^export\s+/gm, "");

const bundle = [
  "/* Deception Decoder — single-file build. Modular source lives in deception-decoder/ */",
  "(function () {",
  strip("assets/js/engine/taxonomy.js"),
  strip("assets/js/engine/linguistics.js"),
  strip("assets/js/engine/analyzer.js"),
  strip("assets/js/ui/app.js"),
  "})();",
].join("\n\n");

/* The template lives in src/page.html — NOT at the repo root.
   Reading index.html here made the build self-consuming: after the first run the
   root file is already inlined, the <link>/<script> placeholders are gone, both
   replacements silently no-op, and every later build re-emits the stale page
   while still reporting success. That shipped once; the guards below exist so it
   cannot ship twice. */
const TEMPLATE = "src/page.html";
const CSS_TAG = '<link rel="stylesheet" href="assets/css/decoder.css">';
const JS_TAG = '<script type="module" src="assets/js/ui/app.js"></script>';

const template = read(TEMPLATE);
for (const [tag, name] of [[CSS_TAG, "stylesheet link"], [JS_TAG, "module script"]]) {
  if (!template.includes(tag)) {
    console.error(`✗ ${TEMPLATE} is missing its ${name} placeholder — nothing would be inlined.`);
    process.exit(1);
  }
}

const html = template
  .replace(CSS_TAG, () => `<style>\n${read("assets/css/decoder.css")}\n</style>`)
  .replace(JS_TAG, () => `<script>\n${bundle}\n</script>`);

writeFileSync(join(ROOT, "decoder", "index.html"), html);

/* Also emit a classic-script engine bundle so other pages on the site
   (the Gaslight console) can use the same analyzer without ES modules. */
writeFileSync(join(ROOT, "assets", "engine.bundle.js"),
  "/* Generated by build-standalone.js — do not edit. */\n(function (root) {\n" +
  strip("assets/js/engine/taxonomy.js") + "\n" +
  strip("assets/js/engine/linguistics.js") + "\n" +
  strip("assets/js/engine/analyzer.js") + "\n" +
  "root.DecoderEngine = { analyze, toReport, TAXONOMY, FAMILIES };\n})(window);\n");

// Guard 1: catches the $-splice bug (String.replace treats $$ / $& as patterns).
const decls = (html.match(/const \$ = sel/g) || []).length;
if (decls !== 1) {
  console.error(`✗ build corrupt: expected 1 '$' declaration, found ${decls}`);
  process.exit(1);
}
// Guard 2: the output must actually carry the current engine, not a stale copy.
const classes = (read("assets/js/engine/taxonomy.js").match(/^\s{4}id: "/gm) || []).length;
const inlined = (html.match(/^\s{4}id: "/gm) || []).length;
if (inlined !== classes) {
  console.error(`✗ build stale: taxonomy has ${classes} classes but output has ${inlined}`);
  process.exit(1);
}
console.log(`✓ decoder/index.html — ${(html.length / 1024).toFixed(1)} KB, self-contained`);
